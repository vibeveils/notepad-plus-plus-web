"""Write docs/js/version.js with the Notepad++, Scintilla and Lexilla versions of the source tree."""
import re, subprocess, sys, json
npp, out = sys.argv[1], sys.argv[2]
res = open(f'{npp}/PowerEditor/src/resource.h', encoding='utf-8', errors='replace').read()
m = re.search(r'#define VERSION_PRODUCT_VALUE L"([\d.]+)', res)
def ver(path):
    v = open(path).read().strip()
    return '.'.join(v) if v.isdigit() else v
try:
    commit = subprocess.check_output(['git', '-C', npp, 'rev-parse', 'HEAD'], text=True).strip()
except Exception:
    commit = ''
info = {'npp': m.group(1) if m else '?', 'scintilla': ver(f'{npp}/scintilla/version.txt'),
        'lexilla': ver(f'{npp}/lexilla/version.txt'), 'commit': commit}
open(out, 'w').write('// Generated by tools/gen_version.py\nexport const BUILD = ' + json.dumps(info) + ';\n')
print(info)
